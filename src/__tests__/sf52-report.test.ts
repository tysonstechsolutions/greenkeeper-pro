// The generator fetches the fillable form from /templates/ (client-side in
// the app); for the test, serve it from disk.
beforeAll(() => {
  globalThis.fetch = (async (url: unknown) => {
    if (String(url).includes("sf52-form.pdf")) {
      return new Response(readFileSync("public/templates/sf52-form.pdf"));
    }
    throw new Error(`unexpected fetch: ${url}`);
  }) as typeof fetch;
});

